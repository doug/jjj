//! On-disk format compatibility with older releases.
//!
//! jjj's metadata is markdown-with-frontmatter in a jj bookmark. Users upgrade
//! the binary; they do not migrate their repository. So every field a past
//! release wrote must still load — and the schema has moved: `force_accepted`
//! became `force_approved`, five free-form fields (`context`, `tradeoffs`,
//! `evidence`, `goals`, `success_criteria`) were folded into the body, and the
//! relational back-references (`solution_ids`, `critique_ids`, `problem_ids`,
//! `child_ids`) stopped being stored and became derived.
//!
//! The corpora under `tests/fixtures/corpus-*` were generated by *actually
//! building* the release in question and running it — not hand-written to match
//! what we remember the schema being, which would test our memory rather than
//! the format. Regenerate with the recipe in `tests/fixtures/README.md`.

mod test_helpers;

use std::fs;
use std::path::{Path, PathBuf};

use test_helpers::{jj_available, run_jjj, run_jjj_success, setup_test_repo};

fn fixture_dir(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join(name)
}

/// Copy a fixture corpus over a freshly-initialized repo's metadata, as an
/// upgrade would find it.
fn repo_from_fixture(name: &str) -> tempfile::TempDir {
    let repo = setup_test_repo();
    let meta = repo.path().join(".jj/jjj-meta");
    let src = fixture_dir(name);
    assert!(
        src.exists(),
        "missing fixture corpus {} — see tests/fixtures/README.md",
        src.display()
    );

    for entry in fs::read_dir(&src).expect("read fixture") {
        let entry = entry.expect("fixture entry");
        let dest = meta.join(entry.file_name());
        if entry.path().is_dir() {
            fs::create_dir_all(&dest).ok();
            for file in fs::read_dir(entry.path()).expect("read fixture subdir") {
                let file = file.expect("fixture file");
                fs::copy(file.path(), dest.join(file.file_name())).expect("copy fixture file");
            }
        } else {
            fs::copy(entry.path(), &dest).expect("copy fixture file");
        }
    }

    drop_derived_cache(repo.path());
    repo
}

/// Remove the SQLite cache so reads come from the canonical markdown.
///
/// An older release's DB carries an older `schema_version` and is rebuilt on
/// first use, so an upgrade always reads the files first. A test that installs
/// entity files behind jjj's back has to do the same: the freshly-initialized
/// DB is empty *and clean*, so leaving it in place makes every read serve zero
/// entities and every assertion fail for the wrong reason.
fn drop_derived_cache(repo: &Path) {
    for suffix in ["", "-wal", "-shm"] {
        let _ = fs::remove_file(repo.join(format!(".jj/jjj.db{suffix}")));
    }
}

/// Every corpus must satisfy the same baseline: it loads, and nothing is lost.
fn assert_corpus_loads(corpus: &str) {
    let repo = repo_from_fixture(corpus);

    let problems = run_jjj_success(repo.path(), &["problem", "list"]);
    assert!(
        problems.contains("Session tokens never expire"),
        "{corpus}: problems did not load:\n{problems}"
    );
    assert!(
        problems.contains("Slow dashboard"),
        "{corpus}: second problem missing:\n{problems}"
    );

    let solutions = run_jjj_success(repo.path(), &["solution", "list"]);
    assert!(
        solutions.contains("Add a 24h TTL"),
        "{corpus}: solutions did not load:\n{solutions}"
    );

    let critiques = run_jjj_success(repo.path(), &["critique", "list"]);
    assert!(
        critiques.contains("Refresh tokens need rotation"),
        "{corpus}: critiques did not load:\n{critiques}"
    );

    let milestones = run_jjj_success(repo.path(), &["milestone", "list"]);
    assert!(
        milestones.contains("v1.0"),
        "{corpus}: milestones did not load:\n{milestones}"
    );
}

