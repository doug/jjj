#[test]
fn a_0_4_corpus_keeps_its_scalar_fields() {
    if !jj_available() {
        return;
    }
    let repo = repo_from_fixture("corpus-0.4");
    let json = run_jjj_success(repo.path(), &["problem", "list", "--json"]);

    // Priority, status and tags are user-authored data. Silently defaulting any
    // of them on load would look like a working upgrade and quietly rewrite the
    // user's board.
    assert!(
        json.contains("\"priority\": \"critical\""),
        "priority lost: {json}"
    );
    assert!(
        json.contains("\"priority\": \"medium\""),
        "priority lost: {json}"
    );
    assert!(
        json.contains("\"status\": \"in_progress\""),
        "status lost: {json}"
    );
    assert!(json.contains("security"), "tags lost: {json}");
    assert!(json.contains("auth"), "tags lost: {json}");
}

#[test]
fn stored_back_references_still_resolve_after_they_became_derived() {
    if !jj_available() {
        return;
    }
    let repo = repo_from_fixture("corpus-0.4");

    // 0.4 wrote `solution_ids` / `critique_ids` / `problem_ids` into the file.
    // 0.5 derives them from the forward references instead. The old keys are
    // now unknown to the schema, and the relationships must survive anyway —
    // via the `problem_id` / `solution_id` / `milestone_id` on the other side.
    let json = run_jjj_success(repo.path(), &["solution", "list", "--json"]);
    assert!(
        json.contains("problem_id"),
        "the forward reference is what derivation depends on: {json}"
    );

    let shown = run_jjj_success(repo.path(), &["problem", "show", "Session tokens"]);
    assert!(
        shown.contains("Add a 24h TTL"),
        "a solution stored under the old back-reference no longer links to its \
         problem:\n{shown}"
    );

    let milestone = run_jjj_success(repo.path(), &["milestone", "show", "v1.0"]);
    assert!(
        milestone.contains("Slow dashboard"),
        "milestone membership lost on upgrade:\n{milestone}"
    );
}

#[test]
fn an_old_corpus_round_trips_without_losing_fields() {
    if !jj_available() {
        return;
    }
    let repo = repo_from_fixture("corpus-0.4");

    // Editing one entity must not strip fields from it — or from anything else
    // the command happens to rewrite.
    run_jjj_success(
        repo.path(),
        &["problem", "edit", "Slow dashboard", "--priority", "high"],
    );

    let json = run_jjj_success(repo.path(), &["problem", "list", "--json"]);
    assert!(
        json.contains("\"priority\": \"high\""),
        "edit did not apply"
    );
    assert!(
        json.contains("\"priority\": \"critical\""),
        "editing one problem changed another: {json}"
    );

    let after = run_jjj_success(repo.path(), &["problem", "list", "--json"]);
    assert!(after.contains("security"), "tags lost on save: {after}");
}

#[test]
fn the_legacy_force_accepted_key_is_still_accepted() {
    if !jj_available() {
        return;
    }
    let repo = setup_test_repo();

    // The rename shipped with a serde alias. Nothing tested the alias, so a
    // future cleanup could drop it and break every pre-rename repository.
    let id = "01900000-0000-7000-8000-000000000001";
    let problem_id = "01900000-0000-7000-8000-000000000002";
    fs::write(
        repo.path()
            .join(".jj/jjj-meta/problems")
            .join(format!("{problem_id}.md")),
        format!(
            "---\nid: '{problem_id}'\ntitle: Ancient problem\nstatus: open\npriority: medium\n\
             created_at: '2026-01-01T00:00:00Z'\nupdated_at: '2026-01-01T00:00:00Z'\n---\n"
        ),
    )
    .expect("write problem");
    fs::write(
        repo.path()
            .join(".jj/jjj-meta/solutions")
            .join(format!("{id}.md")),
        format!(
            "---\nid: '{id}'\ntitle: Ancient solution\nproblem_id: '{problem_id}'\n\
             status: approved\nforce_accepted: true\ncreated_at: '2026-01-01T00:00:00Z'\n\
             updated_at: '2026-01-01T00:00:00Z'\n---\n"
        ),
    )
    .expect("write solution");
    drop_derived_cache(repo.path());

    let out = run_jjj(repo.path(), &["solution", "list"]);
    let combined = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        combined.contains("Ancient solution"),
        "the force_accepted alias was dropped, breaking pre-rename repos: {combined}"
    );
}

#[test]
fn removed_free_form_fields_do_not_break_loading() {
    if !jj_available() {
        return;
    }
    let repo = setup_test_repo();

    // `context`, `tradeoffs`, `evidence`, `goals` and `success_criteria` were
    // removed in favour of the body. Old files still carry them, and an unknown
    // key must be ignored rather than failing the parse — otherwise upgrading
    // makes the whole repository unreadable.
    let id = "01900000-0000-7000-8000-000000000003";
    fs::write(
        repo.path()
            .join(".jj/jjj-meta/problems")
            .join(format!("{id}.md")),
        format!(
            "---\nid: '{id}'\ntitle: Problem with retired fields\nstatus: open\n\
             priority: high\ncontext: 'Discovered during the incident'\n\
             success_criteria: 'p99 under 200ms'\ngoals:\n- 'Reduce latency'\n\
             created_at: '2026-01-01T00:00:00Z'\nupdated_at: '2026-01-01T00:00:00Z'\n---\n\
             The dashboard is slow.\n"
        ),
    )
    .expect("write problem");
    drop_derived_cache(repo.path());

    let listed = run_jjj_success(repo.path(), &["problem", "list"]);
    assert!(
        listed.contains("Problem with retired fields"),
        "a retired field made the entity unloadable: {listed}"
    );

    let shown = run_jjj_success(repo.path(), &["problem", "show", "retired fields"]);
    assert!(
        shown.contains("The dashboard is slow."),
        "the body should still render: {shown}"
    );
}

#[test]
fn the_cache_can_be_built_from_an_old_corpus() {
    if !jj_available() {
        return;
    }
    let repo = repo_from_fixture("corpus-0.4");

    // The DB is derived, so an upgrade rebuilds it from files written by the
    // older release. A schema mismatch here turns search and status into
    // silently-empty results rather than an error.
    run_jjj_success(repo.path(), &["db", "rebuild"]);

    let searched = run_jjj_success(repo.path(), &["search", "session"]);
    assert!(
        searched.contains("Session tokens never expire"),
        "the rebuilt index does not see the migrated corpus:\n{searched}"
    );
}
